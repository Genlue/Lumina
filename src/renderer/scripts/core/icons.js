/** 取图标 SVG 字符串。名字不存在时回退空心圆，避免布局塌陷。 */
export function icon(name, size = 16, cls = "") {
  const d = PATHS[name] ?? '<circle cx="12" cy="12" r="9"/>';
  return `<svg class="ic ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${d}</svg>`;
}

/** 返回一个真实的 SVG 元素节点 */
export function iconEl(name, size = 16, cls = "") {
  const t = document.createElement("template");
  t.innerHTML = icon(name, size, cls).trim();
  return t.content.firstElementChild;
}

/** 把 root 内所有 [data-icon] 占位元素就地替换为 SVG */
export function mountIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    if (el.dataset.iconMounted) return;
    el.innerHTML = icon(el.dataset.icon, Number(el.dataset.size || 16));
    el.dataset.iconMounted = "1";
  });
}

